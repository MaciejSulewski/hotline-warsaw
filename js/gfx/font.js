    'Ż': G('..#.. ..... ##### ...#. ..#.. .#... #####'),
    0: G('.###. #...# #..## #.#.# ##..# #...# .###.'),
    1: G('..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###.'),
    2: G('.###. #...# ....# ...#. ..#.. .#... #####'),
