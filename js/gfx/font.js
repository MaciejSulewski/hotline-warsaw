    L: G('#.... #.... #.... #.... #.... #.... #####'),
    M: G('#...# ##.## #.#.# #.#.# #...# #...# #...#'),
    N: G('#...# #...# ##..# #.#.# #..## #...# #...#'),
    O: G('.###. #...# #...# #...# #...# #...# .###.'),
    P: G('####. #...# #...# ####. #.... #.... #....'),
    Q: G('.###. #...# #...# #...# #.#.# #..#. .##.#'),
    R: G('####. #...# #...# ####. #.#.. #..#. #...#'),
    S: G('.#### #.... #.... .###. ....# ....# ####.'),
    T: G('##### ..#.. ..#.. ..#.. ..#.. ..#.. ..#..'),
    U: G('#...# #...# #...# #...# #...# #...# .###.'),
    V: G('#...# #...# #...# #...# #...# .#.#. ..#..'),
    W: G('#...# #...# #...# #.#.# #.#.# #.#.# .#.#.'),
    X: G('#...# #...# .#.#. ..#.. .#.#. #...# #...#'),
    Y: G('#...# #...# .#.#. ..#.. ..#.. ..#.. ..#..'),
    Z: G('##### ....# ...#. ..#.. .#... #.... #####'),
    'Ą': G('.###. #...# ##### #...# #...# ...#. ...##'),
    'Ć': G('...#. ..... .###. #.... #.... #.... .###.'),
    'Ę': G('##### #.... ####. #.... ##### ...#. ...##'),
    'Ł': G('.#... .#... .#.#. .##.. ##... .#... .####'),
    'Ń': G('...#. ..... #...# ##..# #.#.# #..## #...#'),
